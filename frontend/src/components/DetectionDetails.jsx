import React from 'react';

const SCORE_LABELS = {
  platt_calibrated_probability: 'Platt-calibrated probability',
  logistic_probability: 'logistic probability',
  tree_vote_fraction: 'tree vote fraction',
};

const LLM_STATUS_LABELS = {
  generated: 'Response generated by Gemini',
  not_called: 'Not sent to Gemini',
  pending_review: 'Held for review (not sent to Gemini)',
  error: 'Gemini request failed',
};

const pct = (value) => `${(value * 100).toFixed(1)}%`;

/** Values exactly as returned by the backend; rows without data are omitted. */
export default function DetectionDetails({ message }) {
  const rows = [
    ['Classification', message.classification],
    ['Confidence', typeof message.confidence === 'number' ? pct(message.confidence) : null],
    ['Injection score', typeof message.p_injection === 'number'
      ? `${pct(message.p_injection)} (${SCORE_LABELS[message.score_type] || message.score_type})`
      : null],
    ['Action', message.action],
    ['Classifier', message.classifier],
    ['Reason', message.reason],
    ['LLM', LLM_STATUS_LABELS[message.llm_status]],
    ['Detection latency', typeof message.latency_ms === 'number' ? `${message.latency_ms} ms` : null],
    ['Event ID', message.event_id],
  ].filter(([, value]) => value !== null && value !== undefined && value !== '');

  return (
    <div className="security-details">
      {rows.map(([label, value]) => (
        <div className="detail-row" key={label}>
          <span className="detail-label">{label}</span>
          <span className={`detail-value ${label === 'Action' ? String(value).toLowerCase() : ''}`}>{value}</span>
        </div>
      ))}
    </div>
  );
}
